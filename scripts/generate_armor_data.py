"""Generate the protocol 2225 player armor fields from EndstoneMC/bedrock-data."""

import argparse
from pathlib import Path

from bedrock_source import SOURCE_REVISION, load_json


OUTPUT = Path(__file__).resolve().parents[1] / "src/endpilot/_armor_values_2225.py"


def generate(checkout: Path) -> str:
    values = {}
    for row in load_json(checkout, "items.json")["items"]:
        if "minecraft:is_armor" not in row["tags"]:
            continue
        name = row["name"]
        stats = row["armor_value"], row["toughness_value"]
        if (not name.startswith("minecraft:") or name in values
                or any(type(value) is not int or value < 0 for value in stats)):
            raise ValueError(f"unexpected player armor fields for {name!r}")
        values[name] = stats

    lines = [
        '"""Vanilla player armor and toughness values for protocol 2225."""',
        "",
        "# Generated by scripts/generate_armor_data.py.",
        f"# Source: EndstoneMC/bedrock-data@{SOURCE_REVISION}:items.json",
        "ARMOR_VALUES = {",
    ]
    lines.extend(f"    {name!r}: {stats}," for name, stats in sorted(values.items()))
    return "\n".join([*lines, "}", ""])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("bedrock_data_checkout", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate(args.bedrock_data_checkout)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"{OUTPUT.name} differs from generated data")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
