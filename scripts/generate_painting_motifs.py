"""Generate protocol 2225 painting motif sizes from the Windows BDS 1.26.66.1 catalog."""

import argparse
from hashlib import sha256
import json
from pathlib import Path


CATALOG_SHA256 = "cb30e0d1b4b8c614ce68a2f694a6d320c881bf992776424827a54fbd075f9b3f"
CATALOG = Path(__file__).with_name("painting-motifs-2225.json")
OUTPUT = Path(__file__).resolve().parents[1] / "src/endpilot/_painting_motifs_2225.py"


def generate(catalog: Path) -> str:
    source = catalog.read_text(encoding="utf-8")
    digest = sha256(source.encode("utf-8")).hexdigest()
    if digest != CATALOG_SHA256:
        raise ValueError(f"{catalog} does not match the pinned 2225 catalog (SHA-256 {digest})")
    motifs = json.loads(source)["motifs"]
    lines = [
        '"""Vanilla BDS 1.26.66.1 painting sizes in blocks (protocol 2225)."""',
        "",
        "# Generated by scripts/generate_painting_motifs.py from the archived BDS catalog.",
        "MOTIF_SIZES = {",
    ]
    for motif, data in sorted(motifs.items()):
        width, height = data["blocks"]
        lines.append(f"    {motif!r}: ({width}, {height}),")
    return "\n".join([*lines, "}", ""])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "catalog", type=Path, nargs="?", default=CATALOG,
        help=f"BDS painting catalog JSON (default: {CATALOG.name} beside this script)",
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate(args.catalog)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit(f"{OUTPUT.name} differs from generated data")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
